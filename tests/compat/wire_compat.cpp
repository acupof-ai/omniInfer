#include <iostream>
#include <string>

#include "omniinfer/proto/messages.hpp"

using namespace omniinfer;

namespace {

std::string decode_hex(const std::string& hex) {
  std::string bytes;
  for (size_t index = 0; index < hex.size(); index += 2) {
    bytes.push_back(static_cast<char>(std::stoi(hex.substr(index, 2), nullptr, 16)));
  }
  return bytes;
}

void check_zero_chunk_id(const Message& message, int& failures) {
  const Value encoded = unpack(serialize_message(message));
  const Value* chunk_id = encoded.find("chunk_id");
  if (chunk_id == nullptr || !chunk_id->is_int() || chunk_id->as_int() != 0) {
    std::cerr << "chunk_id=0 was lost during C++ serialization\n";
    ++failures;
  }
}

}  // namespace

int main() {
  int failures = 0;

  // Generated by Python DataReadyMessage.to_dict() + msgspec.msgpack.encode().
  try {
    const Message message = deserialize_message(decode_hex(
        "86a474797065aa646174615f7265616479aa726571756573745f6964a27230aa66726f6d5f737461"
        "6765a161a8746f5f7374616765a162a8646174615f72656681a55f74797065a474657374a86368756e"
        "6b5f696400"));
    const auto* ready = std::get_if<DataReadyMessage>(&message);
    if (ready == nullptr || ready->chunk_id != 0 || ready->is_done) {
      std::cerr << "Python data_ready fields were decoded incorrectly\n";
      ++failures;
    } else {
      check_zero_chunk_id(message, failures);
    }
  } catch (const std::exception& error) {
    std::cerr << "Python data_ready was rejected: " << error.what() << "\n";
    ++failures;
  }

  // Generated by Python StreamMessage.to_dict() + msgspec.msgpack.encode().
  try {
    const Message message = deserialize_message(decode_hex(
        "88a474797065a673747265616daa726571756573745f6964a27230aa66726f6d5f7374616765a161a5"
        "6368756e6ba178a873746167655f6964c0aa73746167655f6e616d65c0a86d6f64616c697479c0a863"
        "68756e6b5f696400"));
    const auto* stream = std::get_if<StreamMessage>(&message);
    if (stream == nullptr || stream->chunk_id != 0) {
      std::cerr << "Python stream fields were decoded incorrectly\n";
      ++failures;
    } else {
      check_zero_chunk_id(message, failures);
    }
  } catch (const std::exception& error) {
    std::cerr << "Python stream was rejected: " << error.what() << "\n";
    ++failures;
  }

  return failures == 0 ? 0 : 1;
}
